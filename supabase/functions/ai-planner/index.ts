/**
 * Study Focus AI — AI Study Planner Edge Function
 *
 * Server-side AI integration using shared OpenRouter client.
 * The AI API key lives in Supabase secrets and is NEVER exposed to the browser.
 * Produces a personalized study schedule via a real LLM,
 * with a clearly-labeled rule-based fallback when the AI provider is unavailable.
 */

import { verifyAuth } from "../_shared/auth.ts";
import { callAI, logUsage, type PlannedSession } from "../_shared/ai-client.ts";

// ============================================================================
// Types
// ============================================================================

interface PlannerRequest {
  subjects: Array<{
    id: string;
    name: string;
    priority: number;
    weeklyTargetHours: number;
    color: string;
    difficulty?: number;
  }>;
  availableDays: number[];
  preferredStartTime: string;
  dailyDurationMinutes: number;
  examDates: Array<{
    date: string;
    subjectId: string | null;
    title: string;
    time?: string;
  }>;
  goals: string;
  timezone: string;
  sessionDurationMinutes?: number;
  breakDurationMinutes?: number;
  longBreakDurationMinutes?: number;
  sessionsBeforeLongBreak?: number;
}

interface PlannerResponse {
  source: "ai" | "fallback";
  model?: string;
  title: string;
  notes?: string;
  sessions: PlannedSession[];
  reasoning?: string;
  usage?: {
    promptTokens: number;
    completionTokens: number;
    totalTokens: number;
  };
  latencyMs?: number;
  estimatedCostUsd?: number;
}

// Re-export PlannedSession from shared client for validation
interface ValidatedSession {
  subjectId: string | null;
  subjectName: string;
  dayOfWeek: number;
  startTime: string;
  endTime: string;
  durationMinutes: number;
  breakAfter: boolean;
  orderIndex: number;
  topic?: string;
  sessionType?: "focus" | "break" | "review" | "exam_prep";
  isFlexible?: boolean;
}

const DEFAULT_SESSION_MINUTES = 25;
const DEFAULT_BREAK_MINUTES = 5;
const DEFAULT_LONG_BREAK_MINUTES = 15;
const DEFAULT_SESSIONS_BEFORE_LONG = 4;

// ============================================================================
// Fallback Planner (Rule-based)
// ============================================================================

function addMinutes(time: string, minutes: number): string {
  const [h, m] = time.split(":").map(Number);
  const total = h * 60 + m + minutes;
  return `${String(Math.floor(total / 60) % 24).padStart(2, "0")}:${String(total % 60).padStart(2, "0")}`;
}

function fallbackPlanner(req: PlannerRequest): PlannerResponse {
  const sessions: PlannedSession[] = [];
  const subjects = [...req.subjects].sort((a, b) => b.priority - a.priority);
  if (subjects.length === 0) {
    return { source: "fallback", title: "No subjects available", sessions: [], notes: "Add subjects first." };
  }

  const sessionMinutes = req.sessionDurationMinutes || DEFAULT_SESSION_MINUTES;
  const breakMinutes = req.breakDurationMinutes || DEFAULT_BREAK_MINUTES;
  const longBreakMinutes = req.longBreakDurationMinutes || DEFAULT_LONG_BREAK_MINUTES;
  const sessionsBeforeLong = req.sessionsBeforeLongBreak || DEFAULT_SESSIONS_BEFORE_LONG;

  let subjectIdx = 0;
  let orderIndex = 0;

  for (const day of req.availableDays) {
    let time = req.preferredStartTime;
    let remaining = req.dailyDurationMinutes;
    let cycles = 0;

    while (remaining >= sessionMinutes) {
      if (cycles > 0) {
        const isLongBreak = cycles % sessionsBeforeLong === 0;
        time = addMinutes(time, isLongBreak ? longBreakMinutes : breakMinutes);
        remaining -= isLongBreak ? longBreakMinutes : breakMinutes;
        if (remaining < sessionMinutes) break;
      }
      const subject = subjects[subjectIdx % subjects.length];
      const endTime = addMinutes(time, sessionMinutes);
      sessions.push({
        subjectId: subject.id,
        subjectName: subject.name,
        dayOfWeek: day,
        startTime: time,
        endTime,
        durationMinutes: sessionMinutes,
        breakAfter: true,
        orderIndex: orderIndex++,
        topic: `Study ${subject.name.toLowerCase()}`,
        sessionType: "focus",
        isFlexible: false,
      });
      time = endTime;
      remaining -= sessionMinutes;
      cycles++;
      subjectIdx++;
    }
  }

  return {
    source: "fallback",
    title: "Study Plan (Fallback)",
    notes: "Generated by rule-based fallback planner. Configure AI for personalized schedules.",
    sessions,
    reasoning: "Subjects distributed by priority across available days with Pomodoro-style breaks.",
  };
}

// ============================================================================
// AI Response Validation
// ============================================================================

function validateSession(session: unknown, validSubjectIds: Set<string>): ValidatedSession | null {
  if (!session || typeof session !== "object") return null;
  const s = session as Record<string, unknown>;

  // Required fields
  if (typeof s.subjectName !== "string" || !s.subjectName.trim()) return null;
  if (typeof s.dayOfWeek !== "number" || s.dayOfWeek < 0 || s.dayOfWeek > 6) return null;
  if (typeof s.startTime !== "string" || !/^\d{2}:\d{2}$/.test(s.startTime)) return null;
  if (typeof s.endTime !== "string" || !/^\d{2}:\d{2}$/.test(s.endTime)) return null;
  if (typeof s.durationMinutes !== "number" || s.durationMinutes <= 0) return null;
  if (typeof s.breakAfter !== "boolean") return null;
  if (typeof s.orderIndex !== "number") return null;

  // Validate subjectId
  let subjectId: string | null = null;
  if (s.subjectId !== null && s.subjectId !== undefined) {
    if (typeof s.subjectId !== "string" || !validSubjectIds.has(s.subjectId)) return null;
    subjectId = s.subjectId;
  }

  // Validate time ordering
  const startMin = parseTime(s.startTime);
  const endMin = parseTime(s.endTime);
  if (endMin <= startMin) return null;
  if (endMin - startMin !== s.durationMinutes) return null;

  // Optional fields with defaults
  const topic = typeof s.topic === "string" ? s.topic : undefined;
  const sessionType = ["focus", "break", "review", "exam_prep"].includes(s.sessionType as string)
    ? (s.sessionType as ValidatedSession["sessionType"])
    : "focus";
  const isFlexible = typeof s.isFlexible === "boolean" ? s.isFlexible : false;

  return {
    subjectId,
    subjectName: s.subjectName.trim(),
    dayOfWeek: s.dayOfWeek,
    startTime: s.startTime,
    endTime: s.endTime,
    durationMinutes: s.durationMinutes,
    breakAfter: s.breakAfter,
    orderIndex: s.orderIndex,
    topic,
    sessionType,
    isFlexible,
  };
}

function parseTime(time: string): number {
  const [h, m] = time.split(":").map(Number);
  return h * 60 + m;
}

function checkOverlaps(sessions: ValidatedSession[]): boolean {
  const byDay = new Map<number, ValidatedSession[]>();
  for (const s of sessions) {
    if (!byDay.has(s.dayOfWeek)) byDay.set(s.dayOfWeek, []);
    byDay.get(s.dayOfWeek)!.push(s);
  }
  for (const [, daySessions] of byDay) {
    daySessions.sort((a, b) => parseTime(a.startTime) - parseTime(b.startTime));
    for (let i = 1; i < daySessions.length; i++) {
      if (parseTime(daySessions[i].startTime) < parseTime(daySessions[i - 1].endTime)) {
        return true; // Overlap detected
      }
    }
  }
  return false;
}

// ============================================================================
// Main Handler
// ============================================================================

export default async function handler(req: Request): Promise<Response> {
  const corsHeaders = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
    "Content-Type": "application/json",
  };

  if (req.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
  if (req.method !== "POST") {
    return new Response(JSON.stringify({ error: "Method not allowed" }), { status: 405, headers: corsHeaders });
  }

  // Verify authentication FIRST - derive userId from JWT
  const auth = await verifyAuth(req);
  if (auth.error) {
    return new Response(JSON.stringify({ error: auth.error }), { status: auth.status, headers: corsHeaders });
  }
  const userId = auth.userId;

  let body: PlannerRequest;
  try {
    body = (await req.json()) as PlannerRequest;
  } catch {
    return new Response(JSON.stringify({ error: "Invalid request body" }), { status: 400, headers: corsHeaders });
  }

  const {
    subjects,
    availableDays,
    preferredStartTime,
    dailyDurationMinutes,
    examDates,
    goals,
    timezone,
    sessionDurationMinutes,
    breakDurationMinutes,
    longBreakDurationMinutes,
    sessionsBeforeLongBreak,
  } = body;

  // Validate required fields (userId now comes from verified JWT, not request body)
  if (!subjects || subjects.length === 0) {
    const fallback = fallbackPlanner({ ...body, userId });
    return new Response(JSON.stringify(fallback), { status: 200, headers: { ...corsHeaders, "x-planner-source": "fallback" } });
  }
  if (!availableDays || availableDays.length === 0) {
    return new Response(JSON.stringify({ error: "No available days specified" }), { status: 400, headers: corsHeaders });
  }

  const validSubjectIds = new Set(subjects.map((s) => s.id));
  const dailyMinutes = dailyDurationMinutes;
  const today = new Date();
  const todayStr = today.toISOString().split("T")[0];

  // Build system prompt for AI
  const systemPrompt = `You are an expert study planner AI. Create a personalized weekly study schedule.

OUTPUT FORMAT: Return ONLY a valid JSON array of session objects. No markdown, no extra text.
[
  {
    "subjectId": "uuid-or-null",
    "subjectName": "string",
    "dayOfWeek": 0-6 (0=Sunday),
    "startTime": "HH:MM",
    "endTime": "HH:MM",
    "durationMinutes": number,
    "breakAfter": boolean,
    "orderIndex": number,
    "topic": "specific study topic",
    "sessionType": "focus|break|review|exam_prep",
    "isFlexible": boolean
  }
]

Rules:
- Total focus time per day must not exceed ${dailyMinutes} minutes (including breaks).
- Use ${sessionDurationMinutes || DEFAULT_SESSION_MINUTES}-minute focus sessions with ${breakDurationMinutes || DEFAULT_BREAK_MINUTES}-minute short breaks.
- After every ${sessionsBeforeLongBreak || DEFAULT_SESSIONS_BEFORE_LONG} focus sessions in a day, add a ${longBreakDurationMinutes || DEFAULT_LONG_BREAK_MINUTES}-minute long break.
- Distribute subjects across available days: ${availableDays.join(", ")} (0=Sun, 6=Sat).
- Prioritize higher priority subjects (1=highest, 5=lowest) and upcoming exams.
- Preferred start time: ${preferredStartTime}.
- Today is ${todayStr}. Upcoming exams: ${JSON.stringify(examDates)}.
- User goals: ${goals || "General study improvement"}.
- Do not assign the same subject to back-to-back blocks; spread study evenly.
- subjectId must match a provided subject (or null for breaks).
- Include specific topics for each session (e.g., "Calculus derivatives", "Biology cell structure").
- sessionType: "focus" for study, "break" for breaks, "review" for review, "exam_prep" for exam prep.

Subjects: ${JSON.stringify(subjects.map(s => ({ id: s.id, name: s.name, priority: s.priority, weeklyTargetHours: s.weeklyTargetHours, difficulty: s.difficulty || 3 })))}`;

  // Try AI generation
  const aiResponse = await callAI<ValidatedSession[]>({
    feature: "planner",
    userId,
    systemPrompt,
    userPrompt: "Generate my weekly study schedule.",
    temperature: 0.3,
    maxTokens: 4000,
    responseFormat: "json",
  });

  // Log usage with verified userId
  await logUsage({
    feature: "planner",
    userId,
    model: aiResponse.model || Deno.env.get("AI_MODEL") || "unknown",
    status: aiResponse.success ? "success" : "error",
    latencyMs: aiResponse.latencyMs,
    promptTokens: aiResponse.usage?.promptTokens,
    completionTokens: aiResponse.usage?.completionTokens,
    totalTokens: aiResponse.usage?.totalTokens,
    estimatedCostUsd: aiResponse.estimatedCostUsd,
    errorMessage: aiResponse.error,
  });

  if (aiResponse.success && aiResponse.data) {
    // Validate each session
    const validatedSessions: ValidatedSession[] = [];
    for (let i = 0; i < aiResponse.data.length; i++) {
      const validated = validateSession(aiResponse.data[i], validSubjectIds);
      if (validated) {
        validatedSessions.push(validated);
      } else {
        console.warn(`[AI Planner] Invalid session at index ${i}:`, aiResponse.data[i]);
      }
    }

    // Check for overlaps
    if (checkOverlaps(validatedSessions)) {
      console.warn("[AI Planner] Overlapping sessions detected, falling back");
      const fallback = fallbackPlanner({ ...body, userId });
      return new Response(JSON.stringify(fallback), { status: 200, headers: { ...corsHeaders, "x-planner-source": "fallback" } });
    }

    // Check daily limits
    const dailyTotals = new Map<number, number>();
    for (const s of validatedSessions) {
      const total = (dailyTotals.get(s.dayOfWeek) || 0) + s.durationMinutes;
      if (s.sessionType !== "break") {
        if (total > dailyMinutes) {
          console.warn(`[AI Planner] Daily limit exceeded for day ${s.dayOfWeek}, falling back`);
          const fallback = fallbackPlanner({ ...body, userId });
          return new Response(JSON.stringify(fallback), { status: 200, headers: { ...corsHeaders, "x-planner-source": "fallback" } });
        }
        dailyTotals.set(s.dayOfWeek, total);
      }
    }

    // Convert to PlannedSession type
    const sessions: PlannedSession[] = validatedSessions.map(s => ({
      subjectId: s.subjectId,
      subjectName: s.subjectName,
      dayOfWeek: s.dayOfWeek,
      startTime: s.startTime,
      endTime: s.endTime,
      durationMinutes: s.durationMinutes,
      breakAfter: s.breakAfter,
      orderIndex: s.orderIndex,
      topic: s.topic,
      sessionType: s.sessionType,
      isFlexible: s.isFlexible,
    }));

    return new Response(
      JSON.stringify({
        source: "ai",
        model: aiResponse.model,
        title: "AI Study Plan",
        notes: "AI-generated personalized study schedule.",
        sessions,
        reasoning: aiResponse.reasoning,
        usage: aiResponse.usage,
        latencyMs: aiResponse.latencyMs,
        estimatedCostUsd: aiResponse.estimatedCostUsd,
      }),
      { status: 200, headers: corsHeaders }
    );
  }

  // Fallback
  console.log(`[AI Planner] AI failed: ${aiResponse.error}. Using fallback.`);
  const fallback = fallbackPlanner({ ...body, userId });
  return new Response(JSON.stringify(fallback), {
    status: 200,
    headers: { ...corsHeaders, "x-planner-source": "fallback" },
  });
}
